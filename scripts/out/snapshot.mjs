// Usage: node scripts/out/snapshot.mjs <outfile>   (baseline / regression snapshot of every headline number)
import fs from 'node:fs';
import crypto from 'node:crypto';
import { buildEngine } from '../../src/engine/index.ts';
import { classify } from '../../src/engine/segments.ts';
const csvPath = new URL('../../public/data/promo_behaviour_data.csv', import.meta.url);
const text = fs.readFileSync(csvPath, 'utf8');
const lines = text.trim().split(/\r?\n/);
const head = lines[0].split(',');
const drop = new Set([head.indexOf('brand'), head.indexOf('product_name')]);
const numeric = lines.map((l) => { const c = l.split(','); if (c.length !== head.length) throw new Error('comma in a field: ' + l); return c.filter((_, i) => !drop.has(i)).join(','); }).join('\n');
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 16);
const e = buildEngine(text);
const sum = (a, f) => a.reduce((x, r) => x + f(r), 0);
const r = (n, d = 4) => Math.round(n * 10 ** d) / 10 ** d;
const types = {}; for (const rec of e.records) types[rec.type] = (types[rec.type] ?? 0) + 1;
const top20 = e.model.gains.find((g) => g.pctCustomers >= 0.2);
const broad = e.strategies.find((s) => /everyone/i.test(s.name)), pers = e.strategies.find((s) => /persuadable/i.test(s.name));
const out = [];
const P = (k, v) => out.push(`${k}: ${typeof v === 'number' ? r(v) : JSON.stringify(v)}`);
P('customers', e.totals.customers); P('orders', e.totals.orders); P('lines', e.totals.lines); P('revenue', e.totals.revenue);
P('campaigns', e.ds.campaigns.length); P('customer types', types);
P('promo units', e.totals.promoUnits); P('incremental share', e.totals.incShare); P('discount cost', e.totals.discountCost);
P('leakage pct', e.totals.leakagePct); P('net profit all campaigns', e.totals.netProfit); P('roi all campaigns', e.totals.roi);
P('AUC test', e.model.aucTest); P('AUC train', e.model.aucTrain ?? null); P('test campaigns', e.model.testCampaigns);
P('top20 capture', top20?.pctResponders ?? null);
P('backtest model net / roi', [pers.netProfit, pers.roi, pers.discountCost]); P('backtest blanket net / roi', [broad.netProfit, broad.roi, broad.discountCost]);
P('validation predicted net', sum(e.validation, (v) => v.predNet)); P('validation actual net', sum(e.validation, (v) => v.realNet));
P('loss avoided (skipped net)', sum(e.validation, (v) => v.skippedNet));
P('group importance', e.model.groupImportance.map((g) => [g.group, r(g.share, 3)]));
const gt = fs.existsSync(new URL('./ground_truth.json', import.meta.url)) ? JSON.parse(fs.readFileSync(new URL('./ground_truth.json', import.meta.url), 'utf8')) : null;
P('planner net by campaign', e.recommendations.map((x) => Math.round(x.best?.net ?? x.net ?? 0)));
P('numeric CSV checksum (all columns except brand, product_name)', sha(numeric));
P('engine numeric digest', sha(JSON.stringify([e.totals, e.model.w, e.model.aucTest, e.results.map((x) => [x.netProfit, x.roi, x.buyers]), e.validation.map((v) => [v.predNet, v.realNet, v.skippedNet, v.broadNet, v.targeted]), e.strategies.map((s) => [s.netProfit, s.roi, s.targeted]), e.stats.map((s) => JSON.stringify(s))])));
fs.writeFileSync(process.argv[2] ?? 'scripts/out/before_snapshot.txt', out.join('\n') + '\n');
console.log(out.join('\n'));
